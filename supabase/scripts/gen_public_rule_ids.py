#!/usr/bin/env python3
"""Generate supabase/functions/_shared/public_rule_ids.ts.

The shared explanation cache (ai_cache) only accepts Bearer, gitleaks, Nuclei and
Checkov rule ids that appear in these scanners' PUBLIC rule sets, at the versions
Trojan pins. Anything else (a project's own bearer.yml rules, an org's checkov
checks, AI-written website templates) is treated as personal and never shared.

Pinned sources (bump together with internal/config/manifest.go, then rerun):
  gitleaks          v8.30.1   config/gitleaks.toml (Trojan's config extends it: useDefault = true)
  bearer            v2.1.3    built-in rules in the bearer source
  bearer-rules      v0.48.4   default rules Bearer downloads at scan time
  checkov           3.4.3     check ids in the checkov source (python and yaml checks)
  nuclei-templates  v10.5.2   template ids (nuclei v3.8.0 uses the latest templates;
                              newer ids are simply not shared until the next bump)

Usage:  python3 supabase/scripts/gen_public_rule_ids.py [--out PATH]
Needs network access to github.com. Output is deterministic (sorted, de-duplicated).
"""
import argparse, io, re, sys, tarfile, urllib.request

PINS = {
    "gitleaks": ("v8.30.1", "https://raw.githubusercontent.com/gitleaks/gitleaks/v8.30.1/config/gitleaks.toml"),
    "bearer": ("v2.1.3", "https://codeload.github.com/Bearer/bearer/tar.gz/refs/tags/v2.1.3"),
    "bearer-rules": ("v0.48.4", "https://codeload.github.com/Bearer/bearer-rules/tar.gz/refs/tags/v0.48.4"),
    "checkov": ("3.4.3", "https://codeload.github.com/bridgecrewio/checkov/tar.gz/refs/tags/3.4.3"),
    "nuclei-templates": ("v10.5.2", "https://codeload.github.com/projectdiscovery/nuclei-templates/tar.gz/refs/tags/v10.5.2"),
}

GITLEAKS_ID = re.compile(r'^\s*id\s*=\s*"([^"]+)"', re.M)
YAML_ID = re.compile(r'^\s*id:\s*["\']?([A-Za-z0-9_.:-]+)["\']?\s*$', re.M)
TOP_YAML_ID = re.compile(r'^id:\s*["\']?([A-Za-z0-9_.:-]+)["\']?\s*$', re.M)
CHECKOV_ID = re.compile(r'\b(CKV2?_[A-Z0-9]+_\d+)\b')


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "trojan-gen-public-rule-ids"})
    with urllib.request.urlopen(req, timeout=300) as r:
        return r.read()


def tar_members(data: bytes):
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tf:
        for m in tf:
            if m.isfile():
                f = tf.extractfile(m)
                if f:
                    yield m.name, f.read()


def gitleaks_ids(toml: str) -> set[str]:
    return set(GITLEAKS_ID.findall(toml))


def bearer_ids(files, only_under: str = "") -> set[str]:
    """Rule ids from Bearer rule yml files: `metadata: id: <id>`. Test fixtures are skipped."""
    out = set()
    for name, body in files:
        if not name.endswith((".yml", ".yaml")):
            continue
        if only_under and only_under not in name:
            continue
        if re.search(r"/(?:testdata|tests?|e2e|fixtures?)/", name):
            continue
        text = body.decode("utf-8", "replace")
        if "metadata:" not in text or "patterns:" not in text and "sanitizer:" not in text and "type:" not in text:
            continue
        for m in YAML_ID.finditer(text):
            rid = m.group(1)
            if re.fullmatch(r"[a-z][a-z0-9_]+", rid):
                out.add(rid)
    return out


def checkov_ids(files) -> set[str]:
    out = set()
    for name, body in files:
        if "/checkov/" not in name or not name.endswith((".py", ".yaml", ".yml", ".json")):
            continue
        if "/tests/" in name or "/test" in name.split("/checkov/", 1)[-1][:6]:
            continue
        out.update(CHECKOV_ID.findall(body.decode("utf-8", "replace")))
    return out


def nuclei_ids(files) -> set[str]:
    out = set()
    for name, body in files:
        if not name.endswith(".yaml") or "/.github/" in name or "/helpers/" in name:
            continue
        m = TOP_YAML_ID.search(body.decode("utf-8", "replace"))
        if m:
            out.add(m.group(1))
    return out


def render(sets: dict[str, set[str]]) -> str:
    lines = [
        "// GENERATED by supabase/scripts/gen_public_rule_ids.py. Do not edit by hand.",
        "// Rule ids from the public rule sets Trojan pins. Only these ids, for these",
        "// scanners, may use the shared explanation cache (ai_cache).",
        "// Sources: " + ", ".join(f"{k} {v[0]}" for k, v in PINS.items()),
        "",
        "export const PUBLIC_RULE_SOURCES = " + repr({k: v[0] for k, v in PINS.items()}).replace("'", '"') + " as const",
        "",
    ]
    for scanner in sorted(sets):
        ids = sorted(sets[scanner])
        lines.append(f"// {scanner}: {len(ids)} ids")
        body = "\\n".join(ids)
        lines.append(f"const {scanner.upper()}_IDS = \"{body}\"")
        lines.append("")
    lines.append("/** Public rule ids per scanner (exact, case-sensitive match). */")
    lines.append("export const PUBLIC_RULE_IDS: Record<string, ReadonlySet<string>> = {")
    for scanner in sorted(sets):
        lines.append(f"  {scanner}: new Set({scanner.upper()}_IDS.split('\\n')),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="supabase/functions/_shared/public_rule_ids.ts")
    a = ap.parse_args()
    sets = {
        "gitleaks": gitleaks_ids(fetch(PINS["gitleaks"][1]).decode()),
        "bearer": bearer_ids(tar_members(fetch(PINS["bearer"][1])), "/rules/built_in/")
                  | bearer_ids(tar_members(fetch(PINS["bearer-rules"][1]))),
        "checkov": checkov_ids(tar_members(fetch(PINS["checkov"][1]))),
        "nuclei": nuclei_ids(tar_members(fetch(PINS["nuclei-templates"][1]))),
    }
    for k, v in sets.items():
        if len(v) < 20:
            sys.exit(f"{k}: only {len(v)} ids, refusing to write a short list")
        bad = [x for x in v if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.:-]{0,199}", x)]
        if bad:
            sys.exit(f"{k}: unexpected id shapes {bad[:5]}")
    open(a.out, "w").write(render(sets))
    print({k: len(v) for k, v in sets.items()})
    return 0


if __name__ == "__main__":
    sys.exit(main())
